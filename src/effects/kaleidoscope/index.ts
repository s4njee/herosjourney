import { gamutMap, oklchToLinear } from '../../gpu/colour/oklab.ts';
import { createFullscreenPipeline, renderFullscreen } from '../../gpu/fullscreen.ts';
import { generateMipmaps, mipLevelCount } from '../../gpu/mipmap.ts';
import { createHdrTail, TAIL_PARAMS } from '../../gpu/post/index.ts';
import { DOSE_PARAMS, dosed } from '../../gpu/safety/dose.ts';
import { withChunks } from '../../gpu/shader.ts';
import { SYMMETRY_GROUPS, type SymmetryGroup } from '../../gpu/symmetry/fold.ts';
import { createUniformBuffer, defineUniformStruct, uniformArray } from '../../gpu/uniforms.ts';
import { defineEffect } from '../types.ts';
import glassShader from './glass.wgsl';
import { meta } from './meta.ts';
import mirrorShader from './mirror.wgsl';

/*
 * Story 4.2. Only the reflection groups are offered: a motif folded through a group is seamless
 * for any motif only when every edge of the fundamental domain is a mirror, which is the dihedral
 * rosettes and the four wallpaper groups generated by reflections (*2222, *442, *333, *632). Every
 * other group has an edge where a rotation or a glide meets, and there an arbitrary motif jumps.
 * Those are the wallpaper lab's (story 4.3), with motifs made for them.
 */

/**
 * The mirror arrangements and the group each generates. `centre` is the middle of the group's
 * fundamental domain (fold.ts) and `span` scales the domain onto the glass, so each arrangement
 * looks at about the same share of it; `cells` evens out the tile sizes on screen.
 */
const MIRRORS = {
  rosette: { group: 'dn', centre: [0.5, 0.14], span: 0.75, cells: 2 },
  square: { group: 'pmm', centre: [0.25, 0.25], span: 1.3, cells: 1 },
  '45-45-90': { group: 'p4m', centre: [0.67, 0.58], span: 1.6, cells: 1 },
  '60-60-60': { group: 'p3m1', centre: [0.3, 0], span: 1.4, cells: 1.15 },
  '30-60-90': { group: 'p6m', centre: [0.3, 0.08], span: 1.9, cells: 1.15 },
} as const satisfies Record<
  string,
  { group: SymmetryGroup; centre: readonly [number, number]; span: number; cells: number }
>;
type MirrorName = keyof typeof MIRRORS;
const MIRROR_NAMES = Object.keys(MIRRORS) as MirrorName[];

const CELL_SIZE = 512;
const SHAPES = 16;
const BEADS = 11;
const SHARDS = 5;
const GOLDEN = 2.399963229728653;

const Params = defineUniformStruct('Params', {
  pan: 'vec2f',
  centre: 'vec2f',
  aspect: 'f32',
  spin: 'f32',
  cells: 'f32',
  group_id: 'f32',
  order: 'f32',
  span: 'f32',
});

const SceneParams = defineUniformStruct('SceneParams', {
  ground: 'vec4f',
  time: 'f32',
  size: 'f32',
  count: 'f32',
  shapes: uniformArray('vec4f', SHAPES),
  colors: uniformArray('vec4f', SHAPES),
});

/** A repeatable number in [0, 1) for shape `i`, channel `k`. */
const hash = (i: number, k: number) => {
  const x = Math.sin(i * 127.1 + k * 311.7) * 43758.5453;
  return x - Math.floor(x);
};

export const effect = defineEffect({
  meta,
  params: {
    ...DOSE_PARAMS,
    mirrors: { type: 'select', default: 'rosette', options: MIRROR_NAMES },
    order: { type: 'number', default: 6, min: 2, max: 16, step: 1, label: 'rosette mirrors' },
    scale: { type: 'number', default: 2.2, min: 0.5, max: 8, step: 0.05, label: 'tiles' },
    hue: { type: 'number', default: 5.4, min: 0, max: 6.28, step: 0.01 },
    speed: { type: 'number', default: 1, min: 0, max: 3, step: 0.05 },
    ...TAIL_PARAMS,
    bloom: { ...TAIL_PARAMS.bloom, default: 0.25 },
  },
  presets: {
    rosette: {},
    'square mirrors': { mirrors: 'square', scale: 2.5 },
    'triangle of 60°': { mirrors: '60-60-60', scale: 2.5, hue: 3.6 },
    'thirty-sixty-ninety': { mirrors: '30-60-90', scale: 2, hue: 0.9 },
    'eight mirrors, slow': { order: 8, dose: 0.2 },
  },

  async create({ device, format, hdr, params, profiler }) {
    const tail = createHdrTail(device, { format, hdr, label: 'kaleidoscope' });
    const levels = mipLevelCount(CELL_SIZE, CELL_SIZE);
    const cell = device.createTexture({
      label: 'kaleidoscope cell',
      size: [CELL_SIZE, CELL_SIZE],
      format: 'rgba16float',
      mipLevelCount: levels,
      usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.RENDER_ATTACHMENT,
    });
    const cellTarget = cell.createView({ baseMipLevel: 0, mipLevelCount: 1 });
    const sampler = device.createSampler({
      addressModeU: 'mirror-repeat',
      addressModeV: 'mirror-repeat',
      magFilter: 'linear',
      minFilter: 'linear',
      mipmapFilter: 'linear',
      maxAnisotropy: 8,
    });

    const scene = createUniformBuffer(device, SceneParams, 'kaleidoscope scene');
    const glass = createFullscreenPipeline(device, {
      fragment: withChunks(glassShader, { 'scene-params.wgsl': SceneParams.wgsl }),
      entryPoint: 'glass',
      format: 'rgba16float',
    });
    const glassGroup = device.createBindGroup({
      layout: glass.getBindGroupLayout(0),
      entries: [{ binding: 0, resource: { buffer: scene.buffer } }],
    });

    const uniforms = createUniformBuffer(device, Params, 'kaleidoscope params');
    const mirror = createFullscreenPipeline(device, {
      fragment: withChunks(mirrorShader, { 'params.wgsl': Params.wgsl }),
      entryPoint: 'mirror',
      format: tail.scene.format,
    });
    const mirrorGroup = device.createBindGroup({
      layout: mirror.getBindGroupLayout(0),
      entries: [
        { binding: 0, resource: { buffer: uniforms.buffer } },
        { binding: 1, resource: cell.createView() },
        { binding: 2, resource: sampler },
      ],
    });

    let aspect = 1;
    let clock = 0;
    let spin = 0;
    const shapes = new Float32Array(SHAPES * 4);
    const colors = new Float32Array(SHAPES * 4);

    return {
      resize(w, h) {
        aspect = w / h;
        tail.resize(w, h);
      },
      frame(time, encoder, target) {
        const dt = time.delta * params.speed;
        clock += dt;
        spin += dt * dosed(params.dose, 0, 0.04, 0.15);
        const drift = dosed(params.dose, 0, 0.025, 0.08);
        const chroma = dosed(params.dose, 0.02, 0.11, 0.2);
        const hueSpeed = dosed(params.dose, 0, 0.03, 0.12);

        for (let i = 0; i < BEADS + SHARDS; i++) {
          const shard = i >= BEADS;
          const w = 0.4 + hash(i, 4);
          shapes.set(
            [
              hash(i, 0) + 0.18 * Math.sin(clock * drift * w * 6 + hash(i, 2) * 6.28),
              hash(i, 1) + 0.18 * Math.cos(clock * drift * w * 5 + hash(i, 3) * 6.28),
              shard ? 0.1 + 0.25 * hash(i, 5) : 0.05 + 0.11 * hash(i, 5),
              shard ? 1 : 0,
            ],
            i * 4,
          );
          const L = 0.55 + 0.25 * hash(i, 6);
          const c = gamutMap(
            oklchToLinear([L, chroma, params.hue + i * GOLDEN + clock * hueSpeed]),
          );
          colors.set([c[0], c[1], c[2], 1], i * 4);
        }
        const ground = gamutMap(oklchToLinear([0.16, chroma * 0.4, params.hue + 0.6]));
        scene.set({
          ground: [ground[0], ground[1], ground[2], 1],
          time: clock,
          size: CELL_SIZE,
          count: BEADS + SHARDS,
          shapes,
          colors,
        });
        scene.upload();
        renderFullscreen(encoder, cellTarget, glass, [glassGroup], {
          timestampWrites: profiler.pass('glass'),
        });
        generateMipmaps(device, cell, encoder);

        const arrangement = MIRRORS[params.mirrors as MirrorName] ?? MIRRORS.rosette;
        const rosette = arrangement.group === 'dn';
        const wander = dosed(params.dose, 0, 0.12, 0.3);
        uniforms.set({
          pan: [0.5 + wander * Math.sin(clock * 0.05), 0.5 + wander * Math.cos(clock * 0.037)],
          aspect,
          spin,
          centre: arrangement.centre,
          cells: rosette ? arrangement.cells : params.scale * arrangement.cells,
          group_id: SYMMETRY_GROUPS.indexOf(arrangement.group),
          order: params.order,
          span: rosette ? arrangement.span * params.scale * 0.45 : arrangement.span,
        });
        uniforms.upload();
        renderFullscreen(encoder, tail.scene.view, mirror, [mirrorGroup], {
          timestampWrites: profiler.pass('mirrors'),
        });
        tail.encode(encoder, target, time, params, profiler);
      },
      destroy() {
        uniforms.destroy();
        scene.destroy();
        cell.destroy();
        tail.destroy();
      },
    };
  },
});
